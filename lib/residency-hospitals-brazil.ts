/** Opção de escape exibida no fim de todo select de hospital. */
export const OTHER_HOSPITAL_OPTION = 'Não encontro meu hospital na lista'

/** Lista de um estado já com a opção de escape no fim. */
export function getResidencyHospitalsByState(uf?: string | null): string[] {
  if (!uf) return []
  const list = RESIDENCY_HOSPITALS_BY_STATE[uf] || []
  return [...list, OTHER_HOSPITAL_OPTION]
}
