export function getEntry(id: string): EcgEntry | undefined {
  return ECG_CATALOG.find((e) => e.id === id)
}

export function searchCatalog(query: string, categoria?: EcgCategory | null): EcgEntry[] {
  const q = query.trim().toLowerCase()
  return ECG_CATALOG.filter((e) => {
    if (categoria && e.categoria !== categoria) return false
    if (!q) return true
    const hay = [e.nome, e.categoria, ...e.tags, e.clinical.resumo].join(' ').toLowerCase()
    return hay.includes(q)
  })
}
